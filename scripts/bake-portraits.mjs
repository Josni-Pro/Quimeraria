import { mkdir, rename, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";

const directory = resolve(process.argv[2] ?? "docs");
const canvasModule = process.env.QUIMERARIA_CANVAS
  ? pathToFileURL(resolve(process.env.QUIMERARIA_CANVAS)).href : "@napi-rs/canvas";
const { createCanvas } = await import(canvasModule);
const fromSource = path => import(pathToFileURL(join(directory, path)).href);
const [{ CARDS, RECIPES }, { createGame, fuseCards }, { paintFusionPortrait }, { PAINTED_FUSIONS, fusionArtKey }] =
  await Promise.all(["catalog.js", "engine.js", "fusion-art.js", "fusion-paintings.js"].map(fromSource));

const output = join(directory, "assets", "fusiones");
await mkdir(output, { recursive: true });
const recipes = new Set(RECIPES.filter(recipe => recipe.art).map(recipe => fusionArtKey(recipe.parents)));
const state = {
  ...createGame(),
  coins: 10_000,
  inventory: Object.fromEntries(CARDS.map(card => [card.id, 2]))
};
const canvas = createCanvas(440, 352);
const manifest = [];
for (const [index, first] of CARDS.entries()) {
  for (const second of CARDS.slice(index)) {
    const key = fusionArtKey([first.id, second.id]);
    if (PAINTED_FUSIONS.has(key) || recipes.has(key)) continue;
    const result = fuseCards(state, first.id, second.id, () => 0);
    if (!result.ok || result.outcome !== "success" || !paintFusionPortrait(canvas, result.card, state, 1, 440, 352)) {
      throw new Error(`Could not draw ${key}.`);
    }
    await writeFile(join(output, key + ".webp"), await canvas.encode("webp", 84));
    manifest.push(key);
  }
}
const manifestPath = join(directory, "fusion-bakes.js");
const lines = ["// Generated by scripts/bake-portraits.mjs.", "export const BAKED_FUSIONS = new Set(["];
for (const key of manifest.sort()) lines.push("  " + JSON.stringify(key) + ",");
lines.push("]);", "");
await writeFile(manifestPath + ".tmp", lines.join("\n"));
await rename(manifestPath + ".tmp", manifestPath);
console.log(`Rendered ${manifest.length} individual WebP portraits.`);
